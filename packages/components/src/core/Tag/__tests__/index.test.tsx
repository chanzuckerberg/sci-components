import { generateSnapshots } from "@chanzuckerberg/story-utils";
import { ThemeProvider } from "@mui/material/styles";
import { SparkleIcon } from "@phosphor-icons/react";
import { composeStories } from "@storybook/react-vite";
import { fireEvent, render, screen } from "@testing-library/react";
import * as stories from "../__storybook__/index.stories";
import Tag, { TAG_LINK_ICON_CLASS } from "..";
import { Theme } from "../../styles";

const { Test } = composeStories(stories);

describe("<Tag />", () => {
  generateSnapshots(stories);

  it("renders Tags component", () => {
    render(<Test />);
    const elements = screen.getAllByTestId("tags");
    expect(elements.length).toBeTruthy();
  });

  it("has no role and no tab stop when nothing happens on click", () => {
    render(<Tag label="Static" data-testid="tag" />);

    const tag = screen.getByTestId("tag");
    expect(tag.tagName).toBe("DIV");
    expect(tag).not.toHaveAttribute("role");
    expect(tag).not.toHaveAttribute("tabindex");
  });

  it("becomes a button that answers the pointer, Enter and Space", () => {
    const onClick = vi.fn();
    render(<Tag label="Filter by species" onClick={onClick} />);

    const tag = screen.getByRole("button", { name: "Filter by species" });
    expect(tag).toHaveAttribute("tabindex", "0");

    fireEvent.click(tag);
    fireEvent.keyDown(tag, { key: "Enter" });
    fireEvent.keyUp(tag, { key: " " });
    expect(onClick).toHaveBeenCalledTimes(3);
  });

  it("renders a link, with the arrow when showLinkIcon is set", () => {
    render(
      <Tag
        href="https://sds.czi.design"
        label="Documentation"
        showLinkIcon
        target="_blank"
      />
    );

    const link = screen.getByRole("link", { name: "Documentation" });
    expect(link).toHaveAttribute("href", "https://sds.czi.design");
    expect(link).toHaveAttribute("rel", "noopener noreferrer");
    expect(link.querySelector(`.${TAG_LINK_ICON_CLASS}`)).toHaveAttribute(
      "aria-hidden",
      "true"
    );
  });

  it("leaves the arrow out unless asked for it", () => {
    render(<Tag href="https://sds.czi.design" label="Documentation" />);

    const link = screen.getByRole("link", { name: "Documentation" });
    expect(link.querySelector(`.${TAG_LINK_ICON_CLASS}`)).toBeNull();
  });

  it("takes itself out of the tab order and ignores Enter when disabled", () => {
    const onClick = vi.fn();
    render(<Tag disabled label="Unavailable" onClick={onClick} />);

    const tag = screen.getByRole("button", { name: "Unavailable" });
    expect(tag).toHaveAttribute("aria-disabled", "true");
    expect(tag).toHaveAttribute("tabindex", "-1");

    fireEvent.keyDown(tag, { key: "Enter" });
    expect(onClick).not.toHaveBeenCalled();
  });

  it("keeps the label as the accessible name of an icon-only tag", () => {
    render(
      <Tag
        icon={<SparkleIcon />}
        iconOnly
        label="Generated by AI"
        onClick={() => {}}
      />
    );

    expect(
      screen.getByRole("button", { name: "Generated by AI" })
    ).toBeInTheDocument();
  });

  it("paints the pair of custom colors it is given", () => {
    render(
      <Tag
        color={["rgb(0, 0, 255)", "rgb(255, 0, 0)"]}
        data-testid="tag"
        label="Custom"
      />
    );

    // The pair is [label, background], and the label color lands on MUI's
    // label element rather than on the root.
    const label = screen.getByText("Custom").parentElement as HTMLElement;

    expect(
      window.getComputedStyle(screen.getByTestId("tag")).backgroundColor
    ).toBe("rgb(255, 0, 0)");
    expect(window.getComputedStyle(label).color).toBe("rgb(0, 0, 255)");
  });

  it("draws an outline tag's border from its intent", () => {
    render(
      <ThemeProvider theme={Theme("light")}>
        <Tag
          color="accent"
          data-testid="tag"
          label="Accent"
          sdsStyle="outline"
        />
      </ThemeProvider>
    );

    expect(window.getComputedStyle(screen.getByTestId("tag")).boxShadow).toBe(
      "inset 0 0 0 1px rgba(78, 24, 204, 0.28)"
    );
  });

  it("is 24px tall by default and 20px tall when small", () => {
    render(
      <ThemeProvider theme={Theme("light")}>
        <Tag data-testid="medium" label="Medium" />
        <Tag data-testid="small" label="Small" size="small" />
      </ThemeProvider>
    );

    expect(window.getComputedStyle(screen.getByTestId("medium")).height).toBe(
      "24px"
    );
    expect(window.getComputedStyle(screen.getByTestId("small")).height).toBe(
      "20px"
    );
  });
});
